const { connect } = require('./browser.cjs');
const fs = require('fs');
const assert = (condition, message) => { if (!condition) throw new Error(message); console.log('PASS ' + message); };
(async()=>{
  const b = await connect();
  const state = () => b.evaluate('window.__structura.state()');
  const bounds = () => b.evaluate('window.__structura.bounds()');
  const inView = parts => parts.every(p=>p.corners.every(c=>Math.abs(c[0])<1 && Math.abs(c[1])<1 && c[2]<1));
  await b.send('Runtime.enable'); await b.send('Log.enable');
  await b.send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  await b.send('Page.navigate',{url:'http://127.0.0.1:5174'});
  await b.wait(2200);
  assert((await state()).parts===10,'10 component groups loaded');
  assert(await b.evaluate('document.querySelectorAll(".part-item").length===10'),'component list renders');
  await b.screenshot('desktop-assembled');
  const initial=await state();
  const r=await b.evaluate('(()=>{const r=document.querySelector("canvas.three-canvas").getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height}})()');
  const x=r.x+r.width*.45,y=r.y+r.height*.45;
  await b.send('Input.dispatchMouseEvent',{type:'mousePressed',x,y,button:'left',clickCount:1});
  for(let i=1;i<=8;i++) await b.send('Input.dispatchMouseEvent',{type:'mouseMoved',x:x+i*12,y:y+i*3,button:'left',buttons:1});
  await b.send('Input.dispatchMouseEvent',{type:'mouseReleased',x:x+96,y:y+24,button:'left',clickCount:1});
  await b.wait(500);
  assert(Math.abs((await state()).camera[0]-initial.camera[0])>.3,'pointer drag rotates camera');
  const beforeZoom=await state();
  await b.send('Input.dispatchMouseEvent',{type:'mouseWheel',x,y,deltaX:0,deltaY:-200});
  await b.wait(500);
  const afterZoom=await state();
  const length=s=>Math.hypot(...s.camera.map((v,i)=>v-s.target[i]));
  assert(length(afterZoom)<length(beforeZoom),'wheel zoom changes camera distance');
  await b.click('#reset-btn'); await b.wait(1600);
  await b.click('#explode-btn'); await b.wait(2600);
  assert((await state()).progress>.99,'one-click full explosion reaches endpoint');
  assert(inView(await bounds()),'all exploded bounds remain in view');
  await b.click('#labels-btn'); await b.screenshot('desktop-exploded');
  const ids=await b.evaluate('[...document.querySelectorAll(".part-item")].map(e=>e.dataset.part)');
  for(const id of ids) {
    await b.click(`[data-part="${id}"]`);
    assert((await state()).selected===id,'list selection '+id);
    assert(await b.evaluate(`document.querySelector('[data-part="${id}"]').getAttribute('aria-pressed')==='true'`),'list highlights '+id);
  }
  await b.click('#reset-btn'); await b.wait(2600);
  assert((await state()).progress===0,'reset fully reassembles');
  assert((await bounds()).every(p=>p.position.every((v,i)=>Math.abs(v-p.assembled[i])<.0001)),'every part returns to assembled coordinates');
  await b.click('#front-view-btn'); await b.wait(1500);
  // Select an actual visible mesh by a pointer click on the center-right lens.
  const r2=await b.evaluate('(()=>{const r=document.querySelector("canvas.three-canvas").getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height}})()');
  await b.send('Input.dispatchMouseEvent',{type:'mousePressed',x:r2.x+r2.w*.60,y:r2.y+r2.h*.47,button:'left',clickCount:1});
  await b.send('Input.dispatchMouseEvent',{type:'mouseReleased',x:r2.x+r2.w*.60,y:r2.y+r2.h*.47,button:'left',clickCount:1});
  const hit=await state();
  assert(Boolean(hit.selected),'clicking 3D mesh selects component');
  assert(await b.evaluate(`document.querySelector('[data-part="${hit.selected}"]').getAttribute('aria-pressed')==='true'`),'model selection syncs list');
  await b.click('#rear-view-btn'); await b.wait(1500);
  assert((await state()).camera[2]<0,'rear view camera');
  await b.screenshot('desktop-rear');
  await b.click('#auto-rotate-btn'); const rotateBefore=await state(); await b.wait(600);
  assert((await state()).autoRotate && Math.abs((await state()).camera[0]-rotateBefore.camera[0])>.1,'automatic rotation');
  await b.click('#auto-rotate-btn');
  await b.click('#sources-btn'); assert(await b.evaluate('document.getElementById("sources-dialog").open'),'source notes open'); await b.click('#close-sources-btn');
  await b.click('#help-btn'); assert(await b.evaluate('document.getElementById("help-dialog").open'),'help opens'); await b.click('#close-help-btn');
  await b.click('#reset-btn'); await b.wait(2000);
  await b.send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  await b.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
  await b.wait(1000);
  await b.evaluate('window.scrollTo(0,0)');
  assert(await b.evaluate('document.documentElement.scrollWidth<=innerWidth'),'mobile no horizontal overflow');
  assert(inView(await bounds()),'mobile assembled bounds in view');
  await b.screenshot('mobile-assembled');
  const touchRect=await b.evaluate('(()=>{const r=document.querySelector("canvas.three-canvas").getBoundingClientRect();return{x:r.x+r.width*.4,y:r.y+r.height*.5}})()');
  const touchBefore=await state();
  await b.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{...touchRect,id:1}]});
  for(let i=1;i<=6;i++) await b.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:touchRect.x+i*10,y:touchRect.y,id:1}]});
  await b.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]}); await b.wait(500);
  assert(Math.abs((await state()).camera[0]-touchBefore.camera[0])>.3,'mobile touch rotates');
  const pinchBefore=await state();
  await b.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:touchRect.x-30,y:touchRect.y,id:1},{x:touchRect.x+30,y:touchRect.y,id:2}]});
  for(let i=1;i<=5;i++) await b.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:touchRect.x-30-i*4,y:touchRect.y,id:1},{x:touchRect.x+30+i*4,y:touchRect.y,id:2}]});
  await b.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]}); await b.wait(500);
  assert(length(await state())<length(pinchBefore),'mobile pinch zoom');
  await b.click('#explode-btn'); await b.wait(2600);
  assert(inView(await bounds()),'mobile full explosion remains visible');
  await b.evaluate('window.scrollTo(0,0)'); await b.screenshot('mobile-exploded');
  await b.click('[data-part="motherboard"]'); assert((await state()).selected==='motherboard','mobile component selection');
  await b.screenshot('mobile-detail');
  // Slider interaction through keyboard is deterministic and exercises native input.
  await b.evaluate('document.getElementById("explode-range").focus()');
  await b.send('Input.dispatchKeyEvent',{type:'keyDown',key:'Home',code:'Home',windowsVirtualKeyCode:36});
  await b.send('Input.dispatchKeyEvent',{type:'keyUp',key:'Home',code:'Home',windowsVirtualKeyCode:36});
  await b.wait(2400); assert((await state()).progress===0,'range control reassembles to 0%');
  const errors=b.events.filter(e=>e.method==='Runtime.exceptionThrown'||(e.method==='Log.entryAdded'&&e.params.entry.level==='error'));
  assert(errors.length===0,'no browser runtime or loading errors');
  fs.writeFileSync(require('path').join(__dirname,'results.json'),JSON.stringify({passed:true,desktop:'1440x1000',mobile:'390x844',state:await state(),errors},null,2));
  b.ws.close();
})().catch(e=>{console.error(e);process.exit(1)});
